"""Pass rush vs. pass protection ratings as of week W-1 (Phase 4, step 2).

From non-scramble dropbacks with a known pressure value (``nflsim.data.dropbacks``),
each team gets, for its offense and its defense:

- ``pressure``: pressure rate (allowed by the offense, generated by the defense);
- ``epa_pressured``: EPA per pressured dropback (gained by the offense, allowed by the
  defense);
- ``epa_clean``: EPA per clean dropback.

Ratings are **deviations from the league average of the same season**, because the
pressure definition changes between seasons (see ``nflsim.data.participation``). Only
games in weeks before W count, and each rating is shrunk toward a prior:

    rating = (team_sum - team_n * league_mean + k * prior) / (team_n + k)
    prior  = carryover * last season's shrunk deviation (0 with no previous season)

``league_mean`` is this season's league average through week W-1, or last season's when
no games have been played yet (``league_<metric>`` columns).
"""

from __future__ import annotations

import polars as pl

from nflsim.config import MATCHUP_METRICS, MatchupMetric, MatchupsConfig

_SIDES = {"off": "offense", "def": "defense"}
# (sum column, count column) in the team-game table for each metric.
METRIC_TOTALS: dict[MatchupMetric, tuple[str, str]] = {
    "pressure": ("pressures", "dropbacks"),
    "epa_pressured": ("epa_pressured_sum", "pressured"),
    "epa_clean": ("epa_clean_sum", "clean"),
}
_TOTALS = ["dropbacks", "pressures", "pressured", "clean", "epa_pressured_sum", "epa_clean_sum"]

MATCHUP_COLUMNS = [f"{side}_{m}" for side in _SIDES for m in MATCHUP_METRICS]
LEAGUE_COLUMNS = [f"league_{m}" for m in MATCHUP_METRICS]


def matchup_game_stats(dropbacks: pl.DataFrame) -> pl.DataFrame:
    """Per team-game and side: dropback, pressure and EPA totals.

    One row per (season, week, game_id, team, side) with ``side`` ``off`` (the team's
    offense) or ``def`` (its defense) and the ``_TOTALS`` columns. Scrambles and
    dropbacks with unknown pressure are left out.
    """
    plays = dropbacks.filter(~pl.col("scramble") & pl.col("pressure").is_not_null())
    pressured = pl.col("pressure")
    frames = [
        plays.group_by("season", "week", "game_id", pl.col(col).alias("team"))
        .agg(
            pl.len().cast(pl.Float64).alias("dropbacks"),
            pressured.sum().cast(pl.Float64).alias("pressures"),
            pressured.sum().cast(pl.Float64).alias("pressured"),
            (~pressured).sum().cast(pl.Float64).alias("clean"),
            pl.col("epa").filter(pressured).sum().alias("epa_pressured_sum"),
            pl.col("epa").filter(~pressured).sum().alias("epa_clean_sum"),
        )
        .with_columns(side=pl.lit(side))
        for side, col in _SIDES.items()
    ]
    return (
        pl.concat(frames)
        .select("season", "week", "game_id", "team", "side", *_TOTALS)
        .sort("season", "week", "game_id", "team", "side")
    )


def _strictly_before(
    targets: pl.DataFrame, weekly: pl.DataFrame, by: list[str], suffix: str
) -> pl.DataFrame:
    """Join each target row with the cumulative totals of weeks before its week."""
    cumulative = (
        weekly.sort("week")
        .with_columns(pl.col(_TOTALS).cum_sum().over(by))
        .rename({c: f"{c}{suffix}" for c in _TOTALS})
    )
    return (
        targets.sort("week")
        .join_asof(
            cumulative,
            on="week",
            by=by,
            strategy="backward",
            allow_exact_matches=False,
            check_sortedness=False,
        )
        .with_columns(pl.col(f"{c}{suffix}").fill_null(0.0) for c in _TOTALS)
    )


def matchup_ratings_as_of(
    stats: pl.DataFrame, targets: pl.DataFrame, config: MatchupsConfig
) -> pl.DataFrame:
    """Ratings for each (season, week, team) in ``targets``, using weeks before W only.

    ``stats`` comes from ``matchup_game_stats``. Returns ``season, week, team``,
    ``MATCHUP_COLUMNS`` (deviations from the league), ``LEAGUE_COLUMNS``,
    ``off_dropbacks``/``def_dropbacks`` (this season's dropbacks behind the rating) and
    ``matchup_prior`` (``prior_season``, or ``league`` when the team has no previous
    season). Null when there is no data at all (no game this or last season).
    """
    keys = targets.select(
        pl.col("season").cast(pl.Int32), pl.col("week").cast(pl.Int32), "team"
    ).unique()
    team_weeks = stats.group_by("season", "week", "team", "side").agg(pl.col(_TOTALS).sum())
    league_weeks = (
        stats.filter(pl.col("side") == "off").group_by("season", "week").agg(pl.col(_TOTALS).sum())
    )
    league_now = _strictly_before(
        keys.select("season", "week").unique(), league_weeks, ["season"], "_lg"
    )
    prev_league = (
        league_weeks.group_by("season")
        .agg(pl.col(_TOTALS).sum())
        .with_columns(pl.col("season") + 1)
        .rename({c: f"{c}_plg" for c in _TOTALS})
    )
    frame = keys.join(league_now, on=["season", "week"], how="left").join(
        prev_league, on="season", how="left"
    )
    league_exprs = []
    for metric, (total, count) in METRIC_TOTALS.items():
        now = pl.col(f"{total}_lg") / pl.col(f"{count}_lg")
        prev = pl.col(f"{total}_plg") / pl.col(f"{count}_plg")
        league_exprs += [
            pl.when(pl.col(f"{count}_lg") > 0).then(now).alias(f"_now_{metric}"),
            prev.alias(f"_prev_{metric}"),
        ]
    frame = frame.with_columns(league_exprs).with_columns(
        pl.coalesce(f"_now_{m}", f"_prev_{m}").alias(f"league_{m}") for m in MATCHUP_METRICS
    )

    for side in _SIDES:
        own = team_weeks.filter(pl.col("side") == side).drop("side")
        frame = _strictly_before(frame, own, ["season", "team"], f"_{side}")
        last_season = (
            own.group_by("season", "team")
            .agg(pl.col(_TOTALS).sum())
            .with_columns(pl.col("season") + 1)
            .rename({c: f"{c}_p{side}" for c in _TOTALS})
        )
        frame = frame.join(last_season, on=["season", "team"], how="left")
        exprs = []
        for metric, (total, count) in METRIC_TOTALS.items():
            k = config.prior_dropbacks[metric]
            n_now, s_now = pl.col(f"{count}_{side}"), pl.col(f"{total}_{side}")
            n_prev, s_prev = pl.col(f"{count}_p{side}"), pl.col(f"{total}_p{side}")
            prev_dev = (s_prev - n_prev * pl.col(f"_prev_{metric}")) / (n_prev + k)
            prior = config.carryover * prev_dev.fill_null(0.0).fill_nan(0.0)
            dev_now = (s_now - n_now * pl.col(f"_now_{metric}")).fill_null(0.0)
            exprs.append(
                pl.when(pl.col(f"league_{metric}").is_not_null())
                .then((dev_now + k * prior) / (n_now + k))
                .alias(f"{side}_{metric}")
            )
        exprs.append(pl.col(f"dropbacks_{side}").alias(f"{side}_dropbacks"))
        frame = frame.with_columns(exprs)

    has_prev = pl.col("dropbacks_poff").is_not_null() | pl.col("dropbacks_pdef").is_not_null()
    return frame.select(
        "season",
        "week",
        "team",
        *MATCHUP_COLUMNS,
        *LEAGUE_COLUMNS,
        "off_dropbacks",
        "def_dropbacks",
        pl.when(has_prev)
        .then(pl.lit("prior_season"))
        .otherwise(pl.lit("league"))
        .alias("matchup_prior"),
    ).sort("season", "week", "team")
